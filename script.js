const languageButtons = document.querySelectorAll('[data-lang]');
const localizedElements = document.querySelectorAll('[data-i18n]');

function setLanguage(language) {
  const dictionary = translations[language];
  localizedElements.forEach((element) => {
    const value = dictionary[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle('active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });
  document.documentElement.lang = language;
  document.title = language === 'en' ? 'MyIdeaProof — Your Ideas. Your Proof.' : 'MyIdeaProof — Ваші ідеї. Ваш доказ.';
  try {
    localStorage.setItem('myideaproof-language', language);
  } catch (error) {
    // The page still works when browser storage is unavailable.
  }
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.lang));
});

let savedLanguage = 'uk';
try {
  savedLanguage = localStorage.getItem('myideaproof-language') || 'uk';
} catch (error) {
  // Use Ukrainian as the default for restricted local files.
}
setLanguage(savedLanguage);
